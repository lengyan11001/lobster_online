def ensure_running_with_bundled_python() -> None:
    """Build .pyc with the same Python runtime that ships in the package."""
    bundled = Path(PYTHON)
    if not bundled.is_file():
        return
    try:
        if Path(sys.executable).resolve() == bundled.resolve():
            return
    except Exception:
        pass
    if os.environ.get("LOBSTER_ENCRYPTED_BUILD_REEXEC") == "1":
        return
    env = os.environ.copy()
    env["LOBSTER_ENCRYPTED_BUILD_REEXEC"] = "1"
    print(f"[BUILD] Re-launching with bundled Python for .pyc compatibility: {bundled}")
    raise SystemExit(
        subprocess.call(
            [str(bundled), str(Path(__file__).resolve()), *sys.argv[1:]],
            cwd=str(PROJECT_ROOT),
            env=env,
        )
    )

